export const translations: Readonly<Record<SupportedLocale, Record<TranslationKey, string>>> = {
  'pt-BR': ptBR,
  en,
  es,
};

export function resolveSupportedLocale(values: readonly string[]): SupportedLocale {
  for (const value of values) {
    const language = value.trim().toLowerCase().split(/[-_]/)[0];
    if (language === 'pt') return 'pt-BR';
    if (language === 'en') return 'en';
    if (language === 'es') return 'es';
  }
  return 'pt-BR';
}

@Injectable({ providedIn: 'root' })
export class I18nService {
  private readonly document = inject(DOCUMENT);
  readonly locale = signal<SupportedLocale>(
    resolveSupportedLocale([this.document.documentElement.lang || 'pt-BR']),
  );

  constructor() {
    effect(() => {
      this.document.documentElement.lang = this.locale();
    });
  }

  setLocale(locale: SupportedLocale): void {
    this.locale.set(locale);
  }

  translate(
    key: TranslationKey,
    parameters: Readonly<Record<string, string | number>> = {},
  ): string {
    const template = translations[this.locale()][key] ?? translations['pt-BR'][key];
    return template.replace(/\{([a-zA-Z][a-zA-Z0-9]*)\}/g, (match, name: string) =>
      Object.hasOwn(parameters, name) ? String(parameters[name]) : match,
    );
  }

  translateMessage(
    key: string,
    parameters: Readonly<Record<string, unknown>>,
    fallback: string,
  ): string {
    return translateCanonicalMessage(this.locale(), key, parameters, fallback);
  }

  formatCurrency(cents: number, currency: string): string {
    const safeCurrency = /^[A-Z]{3}$/.test(currency) ? currency : 'BRL';
    return new Intl.NumberFormat(this.locale(), {
      style: 'currency',
      currency: safeCurrency,
    }).format(cents / 100);
  }

  formatDate(value: Date, options: Intl.DateTimeFormatOptions = {}): string {
    return new Intl.DateTimeFormat(this.locale(), options).format(value);
  }
}
